const assert=require('node:assert/strict');
const M=require('../explore-model.js'),P=require('../pathfinder-model.js');
const data=require('../lexicon.json'),model=M.build(data),before=JSON.stringify([...model.nodes.values(),...model.edges]);
const deck=P.challenges(model);
assert.equal(deck.length,12);assert.equal(new Set(deck.map(c=>c.id)).size,deck.length);
for(const c of deck){
 const solution=P.shortestPath(model,c.start,c.goal);assert.ok(solution.length>=3,c.id);
 assert.equal(solution.length-1,c.shortestSteps,c.id);
 const round=P.createRound(model,c);assert.equal(round.snapshot().reference,null);
 for(const id of solution.slice(1))assert.equal(round.move(id).changed,true,c.id);
 assert.equal(round.snapshot().phase,'completed');assert.equal(round.snapshot().steps,c.shortestSteps);
 assert.deepEqual(round.snapshot().reference,solution);
 assert.equal(round.undo(),false);assert.equal(round.hint(),null);assert.equal(round.reveal(),false);
 assert.equal(round.move(c.start).reason,'finished');
 const shown=P.visibleGraph(model,round.snapshot());
 for(const e of shown.edges)assert.ok(model.adjacency.get(e.source).has(e.target),'No inferred game edges');
 for(const n of shown.nodes)assert.ok(['word','root'].includes(n.kind));
}
const c=deck[0],r=P.createRound(model,c);
assert.equal(r.move(c.goal).reason,'not-adjacent','A word cannot teleport to the target');
assert.equal(r.move('word:missing').changed,false);assert.equal(r.snapshot().steps,0);
assert.equal(r.move(c.start).reason,'current');
assert.equal(r.hint(),'origin:古希腊语:anthropos');assert.equal(r.hint(),'origin:古希腊语:anthropos');
assert.equal(r.snapshot().hintsUsed,1);assert.equal(r.snapshot().steps,0,'Hints never move the player');
const copy=r.snapshot();copy.path.push(c.goal);copy.choices.length=0;
assert.equal(r.snapshot().path.length,1);assert.ok(r.snapshot().choices.length>0);
assert.equal(r.move('origin:古希腊语:philein').changed,true);
assert.equal(r.snapshot().hint,null);assert.equal(r.snapshot().steps,1);
assert.equal(r.undo(),true);assert.equal(r.snapshot().current,c.start);
assert.equal(r.undo(),false);assert.equal(r.rewind(-1),false);assert.equal(r.rewind(1.5),false);
r.move('origin:古希腊语:philein');r.move(c.start);
assert.equal(r.snapshot().steps,2,'A traversed loop counts as two steps');
assert.equal(r.rewind(0),true);assert.equal(r.snapshot().steps,0);
r.move('origin:古希腊语:philein');r.move(c.start);r.move('origin:古希腊语:anthropos');r.move(c.goal);
assert.equal(r.snapshot().steps,4);assert.equal(r.snapshot().shortestSteps,2);
r.restart();assert.equal(r.snapshot().phase,'playing');assert.equal(r.snapshot().hintsUsed,0);
r.reveal();assert.equal(r.snapshot().phase,'revealed');assert.equal(r.snapshot().steps,0);
assert.deepEqual(r.snapshot().reference,[c.start,'origin:古希腊语:anthropos',c.goal]);
assert.equal(r.move(c.goal).reason,'finished');r.restart();assert.equal(r.snapshot().reference,null);
assert.equal(P.shortestPath(model,'word:missing',c.goal),null);
assert.equal(P.shortestPath(model,c.start,'word:equine'),null,'Disconnected word families cannot be paired');
assert.deepEqual(P.shortestPath(model,c.start,c.start),[c.start]);
assert.equal(P.shortestPath(model,'origin:地名:egypt','word:Gypsy'),null,'Proper names are not productive roots in the game');
assert.throws(()=>P.createRound(model,{start:c.start,goal:'word:equine'}),/disconnected/);
assert.throws(()=>P.createRound(model,{start:c.start,goal:c.start}),/different/);
assert.equal(JSON.stringify([...model.nodes.values(),...model.edges]),before,'Playing must not mutate the library graph');
console.log('PASS: 12 reachable challenges, shortest paths, edge-only movement, undo/loops, hints, reference vs completion, isolation and source graph integrity');
